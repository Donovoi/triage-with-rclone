def inventory_observation(name, invocation=None):
    if invocation is None:
        second = "57" if name == "account_listing" else "59"
        end = "2026-10-15T11:59:58.000000Z" if name == "account_listing" else "2026-10-15T12:00:00.000000Z"
        invocation = dict(started_at="2026-10-15T11:59:" + second + ".000000Z", finished_at=end, elapsed_ns=1000000000)
    modified = invocation["started_at"][:-1] + "+00:00"
    implicit = [dict(path="synthetic-bucket/unmarked",modified=modified)] if name=="account_listing" else []
    rows = E.listing_rows(name) + [["excel-safe-v1","Synthetic",row["path"],"",row["modified"],"true","",""] for row in implicit]
    return dict(invocation=deepcopy(invocation), implicit_directories=implicit, rows=rows)


