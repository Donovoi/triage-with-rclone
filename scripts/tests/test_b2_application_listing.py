def exchange(s, method, target, auth, body=b""):
    request = s.begin(method, target, auth, body)
    status, raw = s.response(request, "http://127.0.0.1:1234")
    s.commit(request, status, len(F.response_wire(status, raw)))
    return json.loads(raw) if raw else None


def setup(s):
    token = exchange(s, "GET", "/b2api/v4/b2_authorize_account", BASIC)["authorizationToken"]
    if s.case == "account_listing":
        exchange(s, "POST", "/b2api/v1/b2_list_buckets", token,
                 b'{"accountId":"synthetic-account","bucketId":"synthetic-bucket-id"}')
    else:
        exchange(s, "HEAD", "/file/synthetic-bucket/nested", token)
    return token


